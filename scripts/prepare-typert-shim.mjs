// Build-time Typert protocol declaration shim.
//
// Why this exists: the Typert generator only recognises @Remote /
// TypertRemoteService when their declarations belong to a package registered
// through the face aggregate's project references (see
// packages/typert-protocol in the DSH monorepo). A third-party workspace cannot
// project-reference the published protocol package (it ships lib/ only, no
// tsconfig), so this script materialises a declaration-only package under
// packages/typert-protocol right before generation.
//
// It is a BUILD ARTIFACT, not a second implementation:
//   - build/ is outside pnpm's `packages/*` workspace glob and is gitignored;
//   - the plugin's runtime always resolves the real
//     @deepseek-ai/dsh-typert-protocol from node_modules;
//   - the shim only carries the declarations the generator inspects.
import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const dir = path.join(root, 'packages', 'typert-protocol')
const src = path.join(dir, 'src')

const manifest = {
  name: '@deepseek-ai/dsh-typert-protocol',
  version: '0.2.2-rc.1',
  private: true,
  type: 'module',
  exports: { '.': './src/index.d.ts' },
}

const tsconfig = {
  compilerOptions: {
    target: 'ES2022',
    module: 'ESNext',
    moduleResolution: 'Bundler',
    strict: true,
    skipLibCheck: true,
    composite: true,
    declaration: true,
    emitDeclarationOnly: true,
    rootDir: 'src',
    outDir: 'lib',
  },
  include: ['src/**/*.d.ts'],
}

const declarations = `// Generated by scripts/prepare-typert-shim.mjs — build artifact, never committed.
// Mirrors only the declarations the Typert generator inspects.
import type { Context } from '@deepseek-ai/cordis'

/** Minimal shape the generator inspects for a Remote service base class. */
export declare abstract class TypertRemoteService<T = never> {
  protected constructor(ctx: Context, serviceKey: string, options?: unknown)
}

/** Method decorator marking one Remote endpoint by export name. */
export declare function Remote(name: string): MethodDecorator

type MethodDecorator = (target: object, context: ClassMethodDecoratorContext) => void
`

fs.mkdirSync(src, { recursive: true })
fs.writeFileSync(path.join(dir, 'package.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8')
fs.writeFileSync(path.join(dir, 'tsconfig.json'), `${JSON.stringify(tsconfig, null, 2)}\n`, 'utf8')
fs.writeFileSync(path.join(src, 'index.d.ts'), declarations, 'utf8')
console.log(`[typert-shim] wrote ${path.relative(root, dir)} (ignored build artifact)`)
